#!/usr/bin/env node
/**
 * 前端契约生成器（docs/06 §7「接口类型只允许生成，禁止手写 DTO」）。
 *
 * 两件事：
 *   1. `openapi.json` → `packages/shared/src/api/schema.d.ts`（`openapi-typescript`）
 *   2. 后端权限点 registry → `packages/shared/src/enums/permissions.ts`
 *
 * ⚠️ **为什么第 2 件事要用 Python 出数据**：权限点的单一来源是
 * `backend/app/common/permissions_registry.py`（docs/07 §2.2 要求的"三处一致"之一，
 * ADR-0008）。在 Node 里解析 Python 源码去取 code 是脆弱的 —— 改个引号风格就悄悄
 * 少一个权限点，而少一个权限点的表现是「按钮该隐藏却还显示」，越权风险。
 * 所以这里直接 `python3 -c` 问 registry 要一份 JSON。
 *
 * 用法：
 *   node scripts/generate-frontend-contract.mjs            # 用已存在的 openapi.json
 *   BACKEND_ORIGIN=http://localhost:8000 node scripts/...  # 从运行中的后端拉 openapi.json
 *
 * 幂等：同样输入连跑两次，`git diff` 必须为空（任务卡验收标准）。
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REPO_ROOT = resolve(ROOT, '..')
const BACKEND = resolve(REPO_ROOT, 'backend')
const OPENAPI_JSON = resolve(BACKEND, 'openapi.json')
const SCHEMA_DTS = resolve(ROOT, 'packages/shared/src/api/schema.d.ts')
const PERMISSIONS_TS = resolve(ROOT, 'packages/shared/src/enums/permissions.ts')

const BANNER = '// ⚠️ 本文件由 scripts/generate-frontend-contract.mjs 生成，请勿手改。'
const BANNER_DOCS =
  '// 改完请重跑 `node scripts/generate-frontend-contract.mjs`（docs/06 §7 禁止手写 DTO）。'

function log(message) {
  process.stdout.write(`[gen] ${message}\n`)
}

/**
 * 取 openapi.json。
 *
 * ⚠️ **默认从应用代码直接导出**，而不是复用仓库里那份：仓库里的 `openapi.json`
 * 是一份**可能过期**的副本 —— 后端加了端点而没人重跑生成器时，类型会静默缺一个，
 * 前端表现是"这个接口的类型是 never"，排查要跨前后端两端。直接从
 * `create_app().openapi()` 取永远与代码一致。
 *
 * 设 `BACKEND_ORIGIN` 时改为走 HTTP（用于「导出的是**运行中**那份」的场景，
 * 例如验证代理 / 网关重写后的路径）。两份都写进 `backend/openapi.json`，
 * 提交它是为了让 CI 不依赖一个活着的后端。
 */
async function fetchOpenApi() {
  const origin = process.env['BACKEND_ORIGIN']
  if (origin) {
    const url = `${origin}/openapi.json`
    const response = await fetch(url)
    if (!response.ok) {
      throw new Error(`拉取 ${url} 失败：HTTP ${response.status}`)
    }
    writeFileSync(OPENAPI_JSON, `${await response.text()}\n`, 'utf8')
    log(`已从 ${url} 拉取 openapi.json`)
    return
  }
  const script = `
import json
from app.main import create_app

spec = create_app().openapi()
print(json.dumps(spec, ensure_ascii=False, indent=2, sort_keys=True))
`
  const raw = execFileSync(pythonInterpreter(), ['-c', script], {
    cwd: BACKEND,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
  writeFileSync(OPENAPI_JSON, raw.endsWith('\n') ? raw : `${raw}\n`, 'utf8')
  log('已从应用代码导出 openapi.json（与应用当前状态一致）')
}

function generateSchema() {
  execFileSync('pnpm', ['exec', 'openapi-typescript', OPENAPI_JSON, '-o', SCHEMA_DTS], {
    cwd: ROOT,
    stdio: 'inherit',
  })
  // ⚠️ `openapi-typescript` 每次都会写时间戳之类的差异吗？不会，但它的默认输出
  // 带一个 "This file was auto-generated by openapi-typescript." 头，版本升级可能
  // 变动。所以显式校验文件非空，别让「生成失败」变成一个 0 字节的 schema.d.ts。
  const generated = readFileSync(SCHEMA_DTS, 'utf8')
  if (!generated.includes('paths')) {
    throw new Error(
      `schema.d.ts 生成异常：文件里没有 paths 段（前 200 字：${generated.slice(0, 200)}）`,
    )
  }
  log(`schema.d.ts 已生成（${generated.split('\n').length} 行）`)
}

/** 问后端 registry 要权限点与内置角色。 */
function readContract() {
  const script = `
import json
from app.common.permissions_registry import PERMISSIONS, ROLES, resolve_role_permissions

print(json.dumps({
    "permissions": [
        {"code": p.code, "name": p.name, "module": p.module, "action": p.action}
        for p in PERMISSIONS
    ],
    "roles": [
        {
            "code": r.code,
            "name": r.name,
            "dataScope": r.data_scope.value,
            "permissions": list(resolve_role_permissions(r)),
        }
        for r in ROLES
    ],
}, ensure_ascii=False))
`
  const raw = execFileSync(pythonInterpreter(), ['-c', script], {
    cwd: BACKEND,
    encoding: 'utf8',
    maxBuffer: 8 * 1024 * 1024,
  })
  return JSON.parse(raw)
}

/**
 * 挑 Python 解释器：**优先后端 venv 里的那个**。
 *
 * ⚠️ 踩过的坑：直接用 `python3` 时拿到的是系统 3.8，导入 `app.common.enums`
 * 立刻炸 `cannot import name 'StrEnum' from 'enum'`（本项目要 3.12）。而
 * 报错信息里还混着 apport 的 pyopenssl 栈，跟真实原因毫无关系 —— 极难定位。
 */
function pythonInterpreter() {
  const candidates = [
    resolve(BACKEND, '.venv/bin/python'),
    process.env['PYTHON'] ?? '',
    'python3',
  ].filter((item) => item !== '')
  for (const candidate of candidates) {
    try {
      // ⚠️ 必须用 `major`/`minor` 两个具名属性：`print(sys.version_info[:2])` 输出的是
      // `(3, 12)`（tuple 的 repr 带圆括号），按方括号去分隔符会解析成 `"(3"` → 版本判 0
      const version = execFileSync(
        candidate,
        ['-c', 'import sys; print(sys.version_info.major, sys.version_info.minor)'],
        { encoding: 'utf8' },
      )
      const [major = '0', minor = '0'] = version.trim().split(/\s+/)
      if (Number(major) === 3 && Number(minor) >= 12) return candidate
    } catch {
      // 解释器不存在或不可执行，试下一个
    }
  }
  throw new Error(
    '找不到 Python ≥ 3.12 的解释器：先在 backend 目录执行 `uv sync` 生成 .venv，' +
      '或用 PYTHON 环境变量显式指定（docs/00 表：后端 Python 3.12）',
  )
}

/** 用工作区的 prettier 规范化生成物。
 *
 * ⚠️ 为什么不在生成物上标「生成物」然后丢进 .prettierignore：那样 `format:check`
 * 就不再看它，而**将来某次 prettier 升级改了格式化规则**时，仓库里就会留下一份
 * 用旧规则格式化的生成物 —— diff 里出现大量与本次改动无关的行，review 的人
 * 只能靠"这是生成物"这句话硬压住那一片噪声。直接在生成时格式化，
 * 生成物永远是当前规则的形状。
 */
async function formatWithPrettier(source, filepath) {
  const prettier = await import('prettier')
  const options = { ...(await prettier.resolveConfig(filepath)), filepath }
  return prettier.format(source, options)
}

async function generatePermissions(contract) {
  const permissions = contract.permissions
  const roles = contract.roles

  const lines = []
  lines.push(BANNER)
  lines.push(BANNER_DOCS)
  lines.push('')
  lines.push('/**')
  lines.push(
    ' * 权限点常量（docs/07 §2.2 的第三处，与后端 registry 和 `permissions` 表 seed 保持一致）。',
  )
  lines.push(' *')
  lines.push(' * ⚠️ 三处一致是**闸门 1 的硬要求**（docs/07 §2.2「三处不一致视为闸门 1 失败」）：')
  lines.push(' *   1. `backend/app/common/permissions_registry.py`（单一来源）')
  lines.push(' *   2. `permissions` 表的 seed（迁移 0002 与 `seed_baseline`）')
  lines.push(' *   3. 本文件')
  lines.push(' *')
  lines.push(
    ' * 后端 `tests/modules/test_permission_registry.py::test_frontend_constants_match_registry`',
  )
  lines.push(' * 会断言本文件的 code 集合与 registry **完全相等**，少一个就红。')
  lines.push(' *')
  lines.push(' * 页面用 `v-can` 指令控制显隐，**后端仍然兜底 403** —— 前端隐藏不是安全。')
  lines.push(' */')
  lines.push('')
  lines.push('/** 全部权限点 code。类型由数组推导，新增一档不需要改别处。 */')
  lines.push('export const PERMISSION_CODES = [')
  for (const item of permissions) {
    lines.push(`  '${item.code}',`)
  }
  lines.push('] as const')
  lines.push('')
  lines.push('export type PermissionCode = (typeof PERMISSION_CODES)[number]')
  lines.push('')
  lines.push('/** 权限点 → 界面名（后端 `permissions.name` 的快照，只读不做判断）。 */')
  lines.push('export const PERMISSION_NAMES: Readonly<Record<PermissionCode, string>> = {')
  for (const item of permissions) {
    lines.push(`  '${item.code}': '${item.name}',`)
  }
  lines.push('}')
  lines.push('')
  lines.push('/**')
  lines.push(' * 逐个权限点的具名常量。')
  lines.push(' *')
  lines.push(' * 为什么除了 `PERMISSION_CODES` 还要这一份：模板里写 `v-can="PERM.BASE_CREATE"`')
  lines.push(" * 比写裸字符串 `'base:create'` 更难打错 —— 裸字符串写错了要等运行时 403 才发现，")
  lines.push(' * 具名常量写错了编译就红。')
  lines.push(' */')
  lines.push('export const PERM = {')
  for (const item of permissions) {
    lines.push(`  ${item.code.replace(/[^a-z0-9]/gi, '_').toUpperCase()}: '${item.code}',`)
  }
  lines.push('} as const satisfies Record<string, PermissionCode>')
  lines.push('')
  lines.push('/** 内置角色 code（docs/07 §2.3）。 */')
  lines.push('export const ROLE_CODES = [')
  for (const item of roles) {
    lines.push(`  '${item.code}',`)
  }
  lines.push('] as const')
  lines.push('')
  lines.push('export type RoleCode = (typeof ROLE_CODES)[number]')
  lines.push('')
  lines.push('/**')
  lines.push(' * 角色 → 该角色实际拥有的权限点。')
  lines.push(' *')
  lines.push(' * ⚠️ 这是**快照**，不是运行时真相：用户在后台改了角色授权后这里就过时了。')
  lines.push(' * 因此**只用于测试夹具与「能不能看到入口」的预判**，真正的鉴权在后端')
  lines.push(' * （`AuthContext.has()` 每次请求查库，docs/07 §1.1）。用它做前端唯一判据 = 越权。')
  lines.push(' */')
  lines.push(
    'export const ROLE_PERMISSIONS: Readonly<Record<RoleCode, readonly PermissionCode[]>> = {',
  )
  for (const item of roles) {
    const list = item.permissions.map((code) => `'${code}'`).join(', ')
    lines.push(`  '${item.code}': [${list}],`)
  }
  lines.push('}')
  lines.push('')

  mkdirSync(dirname(PERMISSIONS_TS), { recursive: true })
  const formatted = await formatWithPrettier(lines.join('\n'), PERMISSIONS_TS)
  writeFileSync(PERMISSIONS_TS, formatted, 'utf8')
  log(`permissions.ts 已生成（${permissions.length} 个权限点 / ${roles.length} 个角色）`)
}

async function main() {
  await fetchOpenApi()
  generateSchema()
  await generatePermissions(readContract())
}

main().catch((error) => {
  process.stderr.write(`[gen] 失败：${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
})
